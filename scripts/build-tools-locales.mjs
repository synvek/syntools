function loadJson(p) {
  if (!existsSync(p)) return {};
  return JSON.parse(readFileSync(p, 'utf8'));
}

function collect(value, set = new Set()) {
  if (typeof value === 'string') set.add(value);
  else if (Array.isArray(value)) value.forEach((v) => collect(v, set));
  else if (value && typeof value === 'object') Object.values(value).forEach((v) => collect(v, set));
  return set;
}

function resolve(text, lang, hand, cache) {
  if (Object.prototype.hasOwnProperty.call(hand, text)) return hand[text];
  if (KEEP.has(text)) return text;
  if (SHORT[lang]?.[text]) return SHORT[lang][text];
  if (Object.prototype.hasOwnProperty.call(cache, text)) {
    const c = cache[text];
    // skip quota warnings / identical English for non-keep
    if (c && !String(c).includes('MYMEMORY WARNING') && c !== text) return c;
  }
  // format examples / code-like: keep
  if (/^(e\.g\.|# |label,value|\{|function |select |<|\\\\u|U\+|&#)/i.test(text)) return text;
  if (!/[A-Za-z]/.test(text)) return text;
  return null; // missing
}

function apply(value, lang, hand, cache, missing) {
  if (typeof value === 'string') {
    const t = resolve(value, lang, hand, cache);
    if (t == null) {
      missing.add(value);
      return value; // temporary fallback
    }
    return t;
  }
  if (Array.isArray(value)) return value.map((v) => apply(v, lang, hand, cache, missing));
  if (value && typeof value === 'object') {
    const out = {};
    for (const [k, v] of Object.entries(value)) out[k] = apply(v, lang, hand, cache, missing);
    return out;
  }
  return value;
}

const langs = ['ja', 'fr', 'de'];
const report = {};

for (const lang of langs) {
  const hand = loadJson(path.join(MAPS, `${lang}.json`));
  const cache = loadJson(path.join(CACHE, `${lang}.json`));
  const missing = new Set();
  const translated = apply(en, lang, hand, cache, missing);
  writeFileSync(path.join(CHUNKS, `${lang}-tools.json`), `${JSON.stringify(translated, null, 2)}\n`);
  writeFileSync(path.join(MAPS, `${lang}-missing.json`), `${JSON.stringify([...missing].sort((a, b) => a.length - b.length), null, 2)}\n`);
  report[lang] = { missing: missing.size, hand: Object.keys(hand).length, cache: Object.keys(cache).length };
  console.log(lang, report[lang], '→', `${lang}-tools.json`);
}

writeFileSync(path.join(MAPS, '_report.json'), JSON.stringify(report, null, 2));
