/** Pattern-based translations for common sentence shapes */
function patternTranslate(text, lang) {
  const P = {
    ja: {
      pleaseEnter: (x) => `${x}を入力してください`,
      pleaseChoose: (x) => `${x}を選択してください`,
      pleasePaste: (x) => `${x}を貼り付けてください`,
      pleaseUpload: (x) => `${x}をアップロードしてください`,
      dropOrChoose: (x) => `${x}をドロップまたは選択`,
      failedTo: (x) => `${x}に失敗しました`,
      invalid: (x) => `無効な${x}`,
    },
    fr: {
      pleaseEnter: (x) => `Veuillez saisir ${x}`,
      pleaseChoose: (x) => `Veuillez choisir ${x}`,
      pleasePaste: (x) => `Veuillez coller ${x}`,
      pleaseUpload: (x) => `Veuillez téléverser ${x}`,
      dropOrChoose: (x) => `Déposez ou choisissez ${x}`,
      failedTo: (x) => `Échec : ${x}`,
      invalid: (x) => `${x} invalide`,
    },
    de: {
      pleaseEnter: (x) => `Bitte ${x} eingeben`,
      pleaseChoose: (x) => `Bitte ${x} wählen`,
      pleasePaste: (x) => `Bitte ${x} einfügen`,
      pleaseUpload: (x) => `Bitte ${x} hochladen`,
      dropOrChoose: (x) => `${x} ablegen oder wählen`,
      failedTo: (x) => `Fehlgeschlagen: ${x}`,
      invalid: (x) => `Ungültig: ${x}`,
    },
  }[lang];

  let m;
  if ((m = text.match(/^Please enter (.+)$/i))) return P.pleaseEnter(m[1]);
  if ((m = text.match(/^Please choose (.+)$/i))) return P.pleaseChoose(m[1]);
  if ((m = text.match(/^Please paste (.+)$/i))) return P.pleasePaste(m[1]);
  if ((m = text.match(/^Please upload (.+)$/i))) return P.pleaseUpload(m[1]);
  if ((m = text.match(/^Please provide (.+)$/i))) return P.pleaseEnter(m[1]);
  if ((m = text.match(/^Please complete (.+)$/i))) {
    return { ja: `${m[1]}を完了してください`, fr: `Veuillez compléter ${m[1]}`, de: `Bitte ${m[1]} vervollständigen` }[lang];
  }
  if ((m = text.match(/^Drop or choose (.+)$/i))) return P.dropOrChoose(m[1]);
  if ((m = text.match(/^Failed to (.+)$/i))) return P.failedTo(m[1]);
  if ((m = text.match(/^Invalid (.+)$/i))) return P.invalid(m[1]);
  if ((m = text.match(/^Enter (.+)$/i))) {
    return { ja: `${m[1]}を入力`, fr: `Saisissez ${m[1]}`, de: `${m[1]} eingeben` }[lang];
  }
  if ((m = text.match(/^Paste (.+)$/i))) {
    return { ja: `${m[1]}を貼り付け`, fr: `Collez ${m[1]}`, de: `${m[1]} einfügen` }[lang];
  }
  if (text.endsWith(' & download')) {
    const a = text.replace(/ & download$/i, '');
    return {
      ja: `${a}してダウンロード`,
      fr: `${a} et télécharger`,
      de: `${a} & herunterladen`,
    }[lang];
  }
  return null;
}

function resolve(text, lang, hand) {
  if (Object.prototype.hasOwnProperty.call(hand, text)) return hand[text];
  if (keep.has(text)) return text;
  if (LEX[text]?.[lang]) return LEX[text][lang];
  if (lang === 'ja' && cacheJa[text] && !String(cacheJa[text]).includes('MYMEMORY WARNING') && cacheJa[text] !== text) {
    return cacheJa[text];
  }
  // placeholders-only / symbols
  if (!/[A-Za-z]/.test(text)) return text;
  // code samples / PEM blocks
  if (/^(e\.g\.|# |label,value|\{|function |select |<|\\\\u|U\+|&#|-----BEGIN)/i.test(text)) return text;
  if (/^(1:1|4:3|3:4|16:9|9:16|<< |>> )/.test(text)) return text;
  const pat = patternTranslate(text, lang);
  if (pat) return pat;
  return null;
}

for (const lang of ['ja', 'fr', 'de']) {
  const hand = JSON.parse(readFileSync(path.join(MAPS, `${lang}.json`), 'utf8'));
  const missing = [];
  for (const s of all) {
    const t = resolve(s, lang, hand);
    if (t == null) missing.push(s);
    else hand[s] = t;
  }
  writeFileSync(path.join(MAPS, `${lang}.json`), `${JSON.stringify(hand, null, 2)}\n`);
  writeFileSync(path.join(MAPS, `${lang}-missing.json`), `${JSON.stringify(missing, null, 2)}\n`);
  console.log(lang, 'mapped', Object.keys(hand).length, 'missing', missing.length);
}
