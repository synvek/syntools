/** 把本工具文案合并进 i18next（工具被懒加载时调用，键路径 tools.photo.*） */
export function registerPhotoStrings(instance: {
  addResourceBundle: (
    lng: string,
    ns: string,
    resources: ResourceTree,
    deep: boolean,
    overwrite: boolean,
  ) => void;
}): void {
  for (const [lng, resources] of Object.entries(photoStrings)) {
    instance.addResourceBundle(lng, 'translation', resources, true, true);
  }
}
