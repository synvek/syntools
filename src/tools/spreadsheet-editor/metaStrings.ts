function bundle(row: Row): ResourceTree {
  const sheet: Record<string, string> = {};
  META_STRING_KEYS.forEach((key, index) => {
    const value = row[index];
    if (typeof value !== 'string') throw new Error(`metaStrings: missing key ${key}`);
    sheet[key] = value;
  });
  return { tools: { sheet } };
}

export const metaStrings: Record<string, ResourceTree> = Object.fromEntries(
  Object.entries(ROWS).map(([lng, row]) => [lng, bundle(row)]),
);

/** Merge the name/protection copy into i18next (keys under tools.sheet.*) */
export function registerMetaStrings(instance: Registrar): void {
  for (const [lng, resources] of Object.entries(metaStrings)) {
    instance.addResourceBundle(lng, 'translation', resources, true, true);
  }
}
