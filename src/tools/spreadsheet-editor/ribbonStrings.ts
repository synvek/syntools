interface Registrar {
  addResourceBundle: (
    lng: string,
    ns: string,
    resources: ResourceTree,
    deep: boolean,
    overwrite: boolean,
  ) => void;
}

for (const [lng, extra] of Object.entries(EXTRA_R)) {
  const target = ribbonStrings[lng]?.tools.sheet;
  if (target) target.r = { ...(target.r as StringTree), ...extra };
}

/** Merge the ribbon copy into i18next (called when the tool chunk loads; keys under tools.sheet.*) */
export function registerRibbonStrings(instance: Registrar): void {
  for (const [lng, resources] of Object.entries(ribbonStrings)) {
    instance.addResourceBundle(lng, 'translation', resources, true, true);
  }
}
