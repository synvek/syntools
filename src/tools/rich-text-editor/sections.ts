import {
  DEFAULT_PAGE_SETUP,
  normalizePageSetup,
  pageMetricsToPx,
  resolvePageMetrics,
  type ColumnCount,
  type PageMargins,
  type PageSetupConfig,
  type PageSize,
} from './pageSetup';

/**
 * Multi-section documents (P2-2, M3 ②): model + pure pagination.
 *
 * Word expresses sections as a `w:sectPr` at the **end** of each section; we store the same information
 * on a section-break node that starts a new section, because that maps 1:1 onto the editing model
 * (a node you can insert/delete) instead of a property that only exists after the fact.
 *
 * Design constraints:
 * - `sections.length === 0` is not a legal state: a document always has at least one section, and
 *   older documents without the field migrate into a single section carrying the old `pageSetup`.
 * - Only two start types are supported (next page / continuous). Odd/even and left/right page setups
 *   are out of scope for P2 and are reported through the existing fidelity channels.
 * - "Link to previous" is expressed per part (header / footer), which is exactly how Word behaves:
 *   you can link the header while keeping a different footer.
 */

export type SectionStartType = 'nextPage' | 'continuous';

export interface DocSection {
  id: string;
  /** Page geometry, background, watermark and page numbers of this section */
  pageSetup: PageSetupConfig;
  /** How this section starts relative to the previous one (ignored for the first section) */
  startType: SectionStartType;
  /** `true` = reuse the previous section's header (Word's "link to previous") */
  headerLinked: boolean;
  /** `true` = reuse the previous section's footer */
  footerLinked: boolean;
}

/** A block, tagged with the section it belongs to (0-based) */
export interface SectionedBlock {
  top: number;
  height: number;
  section: number;
}

/** The pagination-relevant part of a section */
export interface SectionBox {
  /** Content height in CSS px */
  contentHeight: number;
  /** Distance between two page tops in this section (sheet height + gap), CSS px */
  advancePx: number;
  startType: SectionStartType;
}

/** Hard cap: a document with more sections than this is almost certainly generated by a bug, not authored */
export const MAX_SECTIONS = 24;

export function createSection(
  id: string,
  pageSetup: PageSetupConfig = DEFAULT_PAGE_SETUP,
  startType: SectionStartType = 'nextPage',
): DocSection {
  return {
    id,
    // `margin` is nested: copy it too, otherwise two sections would share one mutable object
    pageSetup: { ...pageSetup, margin: { ...pageSetup.margin } },
    startType,
    headerLinked: false,
    footerLinked: false,
  };
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null;
}

function clampSectionIndex(sections: readonly DocSection[], index: number): number {
  if (!Number.isFinite(index)) return 0;
  return Math.min(Math.max(0, Math.trunc(index)), sections.length - 1);
}

/** Walk back to the nearest section that owns its own header / footer */
function inheritedValue(
  sections: readonly DocSection[],
  index: number,
  part: 'header' | 'footer',
): string {
  for (let i = index - 1; i >= 0; i -= 1) {
    const section = sections[i];
    const linked = part === 'header' ? section.headerLinked : section.footerLinked;
    if (!linked) return section.pageSetup[part];
  }
  return DEFAULT_PAGE_SETUP[part];
}

/**
 * Effective page setup of one section: linked header / footer parts resolve to the nearest owner.
 * Everything else (size, margins, columns, background, watermark, page numbers) is always local.
 */
export function resolveSectionPageSetup(
  sections: readonly DocSection[],
  index: number,
): PageSetupConfig {
  if (sections.length === 0) return { ...DEFAULT_PAGE_SETUP };
  const at = clampSectionIndex(sections, index);
  const section = sections[at];
  return {
    ...section.pageSetup,
    header: section.headerLinked
      ? inheritedValue(sections, at, 'header')
      : section.pageSetup.header,
    footer: section.footerLinked
      ? inheritedValue(sections, at, 'footer')
      : section.pageSetup.footer,
  };
}

/** Pagination boxes: one per section, with the content height the layout must fit into */
export function sectionBoxesOf(sections: readonly DocSection[]): SectionBox[] {
  return sections.map((section, index) => {
    const px = pageMetricsToPx(resolvePageMetrics(resolveSectionPageSetup(sections, index)));
    return {
      contentHeight: px.contentHeightPx,
      advancePx: px.advancePx,
      startType: section.startType,
    };
  });
}

/**
 * Read a section-break DOM node into a pagination box, using `fallback` when the node carries no
 * (or a broken) page-setup snapshot. Shared by the on-screen pagination and the snapshot PDF so both
 * paths compute the same page count.
 */
export function sectionBoxFromElement(el: Element, fallback: SectionBox): SectionBox {
  const startType: SectionStartType =
    el.getAttribute(SECTION_BREAK_ATTR) === 'continuous' ? 'continuous' : 'nextPage';
  const raw = el.getAttribute(SECTION_SETUP_ATTR);
  if (raw) {
    try {
      const parsed: unknown = JSON.parse(raw);
      if (isRecord(parsed)) {
        const px = pageMetricsToPx(
          resolvePageMetrics(normalizePageSetup(parsed as Partial<PageSetupConfig>)),
        );
        return { contentHeight: px.contentHeightPx, advancePx: px.advancePx, startType };
      }
    } catch {
      // Broken snapshot: inherit the document geometry, the break itself still works
    }
  }
  return { ...fallback, startType };
}

/**
 * Normalize sections from persisted data / imported documents.
 * Never throws and never returns an empty array: an old document without sections becomes one section
 * that keeps its current page setup, so opening it changes nothing.
 */
export function normalizeSections(
  raw: unknown,
  fallback: PageSetupConfig = DEFAULT_PAGE_SETUP,
): DocSection[] {
  if (!Array.isArray(raw) || raw.length === 0) {
    return [createSection('section-1', fallback)];
  }
  const usedIds = new Set<string>();
  const sections: DocSection[] = [];
  for (const [index, item] of raw.slice(0, MAX_SECTIONS).entries()) {
    const record = isRecord(item) ? item : {};
    const rawId = typeof record.id === 'string' ? record.id.trim() : '';
    // Duplicate ids would make section lookups ambiguous; suffix instead of dropping the section
    let id = rawId || `section-${index + 1}`;
    if (usedIds.has(id)) id = `${id}-${index + 1}`;
    usedIds.add(id);
    sections.push({
      id,
      pageSetup: isRecord(record.pageSetup)
        ? normalizePageSetup(record.pageSetup as Partial<PageSetupConfig>)
        : { ...fallback },
      startType: record.startType === 'continuous' ? 'continuous' : 'nextPage',
      // The first section has nothing to link to
      headerLinked: index > 0 && record.headerLinked === true,
      footerLinked: index > 0 && record.footerLinked === true,
    });
  }
  return sections;
}

/**
 * Section-aware pagination: returns the block indices that start a new page (page 1 excluded).
 *
 * Same policy as `planPageBlocks` (blocks are never split; an oversized block overflows instead of
 * looping forever), but the available height changes per section and a `nextPage` section forces a
 * break before its first visible block. A zero-height section-break node therefore defers the forced
 * break to the block that follows it.
 */
export function planSectionedPageBlocks(
  blocks: readonly SectionedBlock[],
  boxes: readonly SectionBox[],
): number[] {
  const first = boxes[0];
  if (!first) return [];
  const starts: number[] = [];
  let section = 0;
  let pageHeight = first.contentHeight;
  let pageStart = 0;
  let forcedBreak = false;

  blocks.forEach((block, index) => {
    if (block.section > section) {
      section = Math.min(block.section, boxes.length - 1);
      pageHeight = boxes[section].contentHeight;
      if (boxes[section].startType === 'nextPage') forcedBreak = true;
    }
    if (block.section < section) return;
    if (block.height <= 0) return;
    if (forcedBreak) {
      forcedBreak = false;
      pageStart = block.top;
      starts.push(index);
      return;
    }
    if (pageHeight <= 0) return;
    if (block.top < pageStart) return;
    const bottom = block.top + block.height;
    if (bottom - pageStart <= pageHeight) return;
    // The first block on a page already exceeds a page: let it overflow without starting a new page
    if (block.top <= pageStart && block.height >= pageHeight) {
      pageStart = bottom;
      return;
    }
    pageStart = block.top;
    starts.push(index);
  });
  return starts;
}

/* ------------------------------------------------------------------ *
 * OOXML mapping (P2-2.4 import; the export side reuses the same fields)
 * ------------------------------------------------------------------ */

/** Word stores lengths in twips: 1/1440 inch */
const MM_PER_TWIP = 25.4 / 1440;

/** Portrait paper sizes in twips (short edge / long edge) */
const PAPER_TWIPS: Record<PageSize, { short: number; long: number }> = {
  A4: { short: 11906, long: 16838 },
  Letter: { short: 12240, long: 15840 },
};

/** What a `w:sectPr` contributes: only the fields actually present in the XML */
export interface ImportedSection {
  pageSetup: Partial<PageSetupConfig>;
  startType: SectionStartType;
  /** `true` = the section has no `w:headerReference`, i.e. it links to the previous section */
  headerLinked: boolean;
  footerLinked: boolean;
}

function twipToMm(twips: number): number {
  return Math.round(twips * MM_PER_TWIP * 10) / 10;
}

function twipAttr(node: Element | undefined, attr: string): number | undefined {
  const raw = node?.getAttribute(attr);
  if (raw === null || raw === undefined || raw === '') return undefined;
  const value = Number.parseFloat(raw);
  return Number.isFinite(value) ? value : undefined;
}

function paperOf(widthTwip: number, heightTwip: number): PageSize {
  const short = Math.min(widthTwip, heightTwip);
  const long = Math.max(widthTwip, heightTwip);
  const letter = PAPER_TWIPS.Letter;
  // 60 twips ≈ 1mm of tolerance: Word rounds page sizes, and A4 vs Letter differ by far more
  return Math.abs(short - letter.short) < 60 && Math.abs(long - letter.long) < 60 ? 'Letter' : 'A4';
}

/**
 * Read `w:sectPr` blocks from `word/document.xml` in document order.
 *
 * Word puts a section's properties at its **end**, so the last entry is the final section; callers
 * that map this onto our "section break starts a section" model must shift by one. mammoth drops
 * `sectPr` entirely, which is why the import path reads the part directly instead of post-processing HTML.
 */
export function parseDocxSections(xml: string): ImportedSection[] {
  if (!xml.trim()) return [];
  const doc = new DOMParser().parseFromString(xml, 'application/xml');
  if (doc.getElementsByTagName('parsererror').length > 0) return [];
  return Array.from(doc.getElementsByTagName('w:sectPr')).map((node) => {
    const pageSetup: Partial<PageSetupConfig> = {};

    const size = node.getElementsByTagName('w:pgSz')[0];
    const width = twipAttr(size, 'w:w');
    const height = twipAttr(size, 'w:h');
    if (width && height) {
      pageSetup.size = paperOf(width, height);
      pageSetup.orientation =
        size?.getAttribute('w:orient') === 'landscape' || width > height ? 'landscape' : 'portrait';
    }

    const margins = node.getElementsByTagName('w:pgMar')[0];
    if (margins) {
      const parsed: Partial<PageMargins> = {};
      const top = twipAttr(margins, 'w:top');
      const right = twipAttr(margins, 'w:right');
      const bottom = twipAttr(margins, 'w:bottom');
      const left = twipAttr(margins, 'w:left');
      if (top !== undefined) parsed.top = twipToMm(top);
      if (right !== undefined) parsed.right = twipToMm(right);
      if (bottom !== undefined) parsed.bottom = twipToMm(bottom);
      if (left !== undefined) parsed.left = twipToMm(left);
      // Partial margins would break the geometry math downstream; only accept a complete set
      if (
        parsed.top !== undefined &&
        parsed.right !== undefined &&
        parsed.bottom !== undefined &&
        parsed.left !== undefined
      ) {
        pageSetup.margin = parsed as PageMargins;
      }
    }

    const columns = node.getElementsByTagName('w:cols')[0];
    const count = Number.parseInt(columns?.getAttribute('w:num') ?? '', 10);
    if (Number.isFinite(count)) {
      pageSetup.columns = Math.min(3, Math.max(1, count)) as ColumnCount;
    }

    if (node.getElementsByTagName('w:titlePg').length > 0) pageSetup.differentFirstPage = true;

    const type = node.getElementsByTagName('w:type')[0];
    return {
      pageSetup,
      startType: type?.getAttribute('w:val') === 'continuous' ? 'continuous' : 'nextPage',
      headerLinked: node.getElementsByTagName('w:headerReference').length === 0,
      footerLinked: node.getElementsByTagName('w:footerReference').length === 0,
    };
  });
}

/* ------------------------------------------------------------------ *
 * Section break DOM node (Tiptap attrs <-> data attributes)
 * ------------------------------------------------------------------ */

/** Attribute names of the section-break node; the editor node and the exporters share them */
export const SECTION_BREAK_ATTR = 'data-section-break';
export const SECTION_SETUP_ATTR = 'data-section-setup';
export const SECTION_HEADER_LINK_ATTR = 'data-section-header-linked';
export const SECTION_FOOTER_LINK_ATTR = 'data-section-footer-linked';

/**
 * Read a section-break node. A malformed or missing setup snapshot falls back to the document setup
 * (the break still works, it just inherits geometry) — never drop the section because of one bad attribute.
 */
export function parseSectionBreakElement(
  el: Element,
  base: PageSetupConfig,
): {
  startType: SectionStartType;
  pageSetup: PageSetupConfig;
  /** `true` = reuse the previous section's header (Word's "link to previous") */
  headerLinked: boolean;
  footerLinked: boolean;
} {
  const startType: SectionStartType =
    el.getAttribute(SECTION_BREAK_ATTR) === 'continuous' ? 'continuous' : 'nextPage';
  const headerLinked = el.getAttribute(SECTION_HEADER_LINK_ATTR) === 'true';
  const footerLinked = el.getAttribute(SECTION_FOOTER_LINK_ATTR) === 'true';
  const raw = el.getAttribute(SECTION_SETUP_ATTR);
  if (!raw) {
    return {
      startType,
      pageSetup: { ...base, margin: { ...base.margin } },
      headerLinked,
      footerLinked,
    };
  }
  try {
    const parsed: unknown = JSON.parse(raw);
    if (isRecord(parsed)) {
      return {
        startType,
        pageSetup: normalizePageSetup(parsed as Partial<PageSetupConfig>),
        headerLinked,
        footerLinked,
      };
    }
  } catch {
    // Fall through to the document setup
  }
  return {
    startType,
    pageSetup: { ...base, margin: { ...base.margin } },
    headerLinked,
    footerLinked,
  };
}

/** A section's content, ready to be handed to an exporter */
export interface SectionSlice {
  pageSetup: PageSetupConfig;
  startType: SectionStartType;
  headerLinked: boolean;
  footerLinked: boolean;
  elements: Element[];
}

/**
 * Split a list of top-level blocks into sections. Empty sections (two breaks in a row) are dropped:
 * Word tolerates them, but an empty `<w:p/>`-only section is pure noise in every consumer.
 */
export function splitSectionNodes(
  nodes: readonly Element[],
  base: PageSetupConfig,
): SectionSlice[] {
  const slices: SectionSlice[] = [];
  let current: SectionSlice = {
    pageSetup: { ...base, margin: { ...base.margin } },
    startType: 'nextPage',
    // The first section has nothing to link to
    headerLinked: false,
    footerLinked: false,
    elements: [],
  };
  const flush = () => {
    if (current.elements.length > 0) slices.push(current);
  };
  for (const node of nodes) {
    if (node.hasAttribute(SECTION_BREAK_ATTR)) {
      const next = parseSectionBreakElement(node, base);
      flush();
      current = { ...next, elements: [] };
      continue;
    }
    current.elements.push(node);
  }
  flush();
  return slices.length > 0
    ? slices
    : [
        {
          pageSetup: { ...base, margin: { ...base.margin } },
          startType: 'nextPage',
          headerLinked: false,
          footerLinked: false,
          elements: [],
        },
      ];
}
